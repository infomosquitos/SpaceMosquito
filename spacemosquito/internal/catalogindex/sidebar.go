package catalogindex

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

// TreeScriptFile is the space's sidebar script, saved/<SPACE>/tree.js. Page
// index.html files load it from "../tree.js" (see contentmd.MarkdownToHTML),
// so a tree change rewrites this one file instead of every page.
const TreeScriptFile = "tree.js"

// treeNode is the compact JSON form of Node embedded in tree.js.
type treeNode struct {
	Title    string      `json:"t"`
	Dir      string      `json:"d"`
	Children []*treeNode `json:"c,omitempty"`
}

func toTreeNodes(ns []*Node) []*treeNode {
	out := make([]*treeNode, 0, len(ns))
	for _, n := range ns {
		out = append(out, &treeNode{Title: n.Title, Dir: n.Dir, Children: toTreeNodes(n.Children)})
	}
	return out
}

// writeTreeScript writes tree.js: the sidebar renderer plus the space's tree
// as JSON (json.Marshal escapes <, > and &, so titles cannot break out).
func writeTreeScript(spaceDir string, tree *Space) error {
	data, err := json.Marshal(struct {
		Key   string      `json:"key"`
		Title string      `json:"title"`
		Roots []*treeNode `json:"roots"`
	}{tree.Key, spaceHeading(tree.Key, tree.Name), toTreeNodes(tree.Roots)})
	if err != nil {
		return fmt.Errorf("encode tree: %w", err)
	}
	js := "/* Generated by SpaceMosquito: page tree sidebar for saved pages. */\n(" + sidebarScript + ")(" + string(data) + ");\n"
	return writeFileAtomic(filepath.Join(spaceDir, TreeScriptFile), []byte(js))
}

// writeFileAtomic replaces path via a temp file so a page loading tree.js
// during a crawl never reads a half-written file.
func writeFileAtomic(path string, b []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// sidebarScript renders the tree into <aside id="sm-nav"> on a page whose
// directory is the current page. It builds the DOM with textContent only and
// does nothing on pages without the hook.
const sidebarScript = `function (tree) {
  var nav = document.getElementById("sm-nav");
  if (!nav) return;
  var file = location.protocol === "file:" ? "index.html" : "";
  var parts = location.pathname.split("/");
  var current = "";
  try { current = decodeURIComponent(parts[parts.length - 2] || ""); } catch (e) {}

  var css = document.createElement("style");
  css.textContent = [
    "body.sm-with-nav { max-width: none; margin: 0; padding: 0; display: grid; grid-template-columns: 300px minmax(0, 1fr); }",
    "#sm-nav { position: sticky; top: 0; height: 100vh; box-sizing: border-box; overflow: auto; padding: 16px 12px; border-right: 1px solid #8884; font-size: 14px; line-height: 1.5; background: Canvas; }",
    "body.sm-with-nav .sm-content { max-width: 960px; padding: 24px 32px; box-sizing: border-box; }",
    "#sm-nav .sm-head { position: sticky; top: -16px; margin: -16px -12px 8px; padding: 16px 12px 8px; background: Canvas; border-bottom: 1px solid #8884; z-index: 1; }",
    "#sm-nav .sm-space { display: block; font-weight: 600; margin-bottom: 8px; text-decoration: none; }",
    "#sm-nav .sm-tools { display: flex; gap: 4px; }",
    "#sm-nav input { flex: 1; min-width: 0; padding: 4px 8px; font: inherit; font-size: 13px; border: 1px solid #8886; border-radius: 4px; background: transparent; color: inherit; }",
    "#sm-nav button, #sm-toggle { font: inherit; font-size: 13px; padding: 2px 8px; border: 1px solid #8886; border-radius: 4px; background: Canvas; color: inherit; cursor: pointer; }",
    "#sm-nav button:hover, #sm-toggle:hover { background: #8882; }",
    "#sm-nav ul { list-style: none; margin: 0; padding-left: 14px; }",
    "#sm-nav > ul { padding-left: 0; }",
    "#sm-nav li { margin: 1px 0; }",
    "#sm-nav li.sm-leaf { padding-left: 20px; }",
    "#sm-nav a { text-decoration: none; }",
    "#sm-nav a:hover { text-decoration: underline; }",
    "#sm-nav a.sm-current { font-weight: 600; background: #8883; border-radius: 3px; box-decoration-break: clone; -webkit-box-decoration-break: clone; }",
    "#sm-nav summary { cursor: pointer; list-style: none; }",
    "#sm-nav summary::-webkit-details-marker { display: none; }",
    "#sm-nav summary::before { content: \"\\25B6\"; display: inline-block; width: 18px; height: 18px; line-height: 18px; margin-right: 2px; font-size: 9px; text-align: center; vertical-align: 1px; border-radius: 4px; opacity: .6; transition: transform .15s; }",
    "#sm-nav details[open] > summary::before { transform: rotate(90deg); }",
    "#sm-nav summary:hover::before { background: #8883; opacity: 1; }",
    "#sm-nav .sm-hidden, #sm-toggle { display: none; }",
    "@media (max-width: 900px) {",
    "  body.sm-with-nav { display: block; }",
    "  body.sm-with-nav .sm-content { padding: 48px 16px 24px; }",
    "  #sm-toggle { display: block; position: fixed; top: 8px; left: 8px; z-index: 2; }",
    "  #sm-nav { display: none; position: fixed; inset: 0 auto 0 0; width: min(320px, 85vw); z-index: 3; box-shadow: 0 0 24px #0006; }",
    "  body.sm-nav-open #sm-nav { display: block; }",
    "}"
  ].join("\n");
  document.head.appendChild(css);

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text) e.textContent = text;
    return e;
  }
  function link(dir, title) {
    var a = el("a", dir === current ? "sm-current" : "", title);
    a.href = "../" + encodeURIComponent(dir) + "/" + file;
    return a;
  }

  var home = el("a", "sm-space", tree.title);
  home.href = "../" + file;
  home.title = "Space home: full tree and content search";
  var tools = el("div", "sm-tools");
  var filter = el("input");
  filter.type = "search";
  filter.placeholder = "Filter pages\u2026";
  filter.setAttribute("aria-label", "Filter pages by title");
  var expand = el("button", "", "\u229E");
  expand.type = "button";
  expand.title = "Expand all";
  var collapse = el("button", "", "\u229F");
  collapse.type = "button";
  collapse.title = "Collapse all";
  tools.appendChild(filter);
  tools.appendChild(expand);
  tools.appendChild(collapse);

  // items: every <li> with its own and its descendants' titles (for the
  // filter); folders: every <details>; path: folders above the current page.
  var items = [], folders = [], path = [], currentLink = null;
  function build(nodes, ul, ancestors) {
    var all = "";
    nodes.forEach(function (n) {
      var li = el("li"), a = link(n.d, n.t), text = n.t.toLowerCase();
      if (n.d === current) {
        currentLink = a;
        path = ancestors.slice();
      }
      if (n.c && n.c.length) {
        var d = el("details"), s = el("summary"), sub = el("ul");
        s.appendChild(a);
        d.appendChild(s);
        d.appendChild(sub);
        li.appendChild(d);
        folders.push(d);
        text += "\n" + build(n.c, sub, ancestors.concat([d]));
      } else {
        li.className = "sm-leaf";
        li.appendChild(a);
      }
      items.push({ li: li, text: text });
      ul.appendChild(li);
      all += "\n" + text;
    });
    return all;
  }
  var root = el("ul");
  build(tree.roots || [], root, []);

  // Default view: the path to the current page is open, as in Confluence.
  function reset() {
    folders.forEach(function (d) { d.open = path.indexOf(d) >= 0; });
    if (currentLink && currentLink.parentElement.tagName === "SUMMARY") currentLink.parentElement.parentElement.open = true;
  }
  function setAll(open) { folders.forEach(function (d) { d.open = open; }); }
  expand.addEventListener("click", function () { setAll(true); });
  collapse.addEventListener("click", function () { setAll(false); });
  filter.addEventListener("input", function () {
    var q = filter.value.trim().toLowerCase();
    items.forEach(function (it) { it.li.classList.toggle("sm-hidden", q !== "" && it.text.indexOf(q) < 0); });
    if (q !== "") setAll(true); else reset();
  });

  var head = el("div", "sm-head");
  head.appendChild(home);
  head.appendChild(tools);
  nav.appendChild(head);
  nav.appendChild(root);
  nav.hidden = false;
  reset();
  document.body.classList.add("sm-with-nav");

  var toggle = el("button", "", "\u2630 Pages");
  toggle.id = "sm-toggle";
  toggle.type = "button";
  toggle.addEventListener("click", function () {
    document.body.classList.toggle("sm-nav-open");
    revealCurrent();
  });
  document.body.appendChild(toggle);
  // Narrow screens: the open drawer covers the toggle; close it on Esc or a
  // click outside it.
  document.addEventListener("click", function (e) {
    if (!nav.contains(e.target) && e.target !== toggle) document.body.classList.remove("sm-nav-open");
  });
  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape") document.body.classList.remove("sm-nav-open");
  });

  // Scroll the current page into view (the narrow-screen drawer is hidden on
  // load, so this runs again when it opens).
  function revealCurrent() {
    if (!currentLink || nav.clientHeight === 0) return;
    var top = currentLink.getBoundingClientRect().top - nav.getBoundingClientRect().top;
    nav.scrollTop += top - nav.clientHeight / 3;
  }
  revealCurrent();
}`
