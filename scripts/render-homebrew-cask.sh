#!/usr/bin/env bash
# Render the Homebrew cask for infomosquitos/homebrew-tap from a release's
# SHA256SUMS. Writes Ruby to stdout.
# Usage: render-homebrew-cask.sh <version> <SHA256SUMS>
#   version: tag or semver (e.g. v0.7.0 or 0.7.0); the cask gets it without "v".
set -euo pipefail

VERSION="${1:?usage: render-homebrew-cask.sh <version> <SHA256SUMS>}"
SUMS="${2:?usage: render-homebrew-cask.sh <version> <SHA256SUMS>}"
VERSION="${VERSION#v}"

sha_for() {
  local sha
  sha="$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$SUMS")"
  if [[ ! "$sha" =~ ^[0-9a-f]{64}$ ]]; then
    echo "render-homebrew-cask: no sha256 for $1 in $SUMS" >&2
    exit 1
  fi
  echo "$sha"
}

SHA_ARM="$(sha_for spacemosquito-darwin-arm64)"
SHA_INTEL="$(sha_for spacemosquito-darwin-amd64)"

cat <<EOF
# Generated by scripts/render-homebrew-cask.sh in infomosquitos/spacemosquito.
# Do not edit by hand: the release workflow overwrites this file.
cask "spacemosquito" do
  arch arm: "arm64", intel: "amd64"

  version "${VERSION}"
  sha256 arm:   "${SHA_ARM}",
         intel: "${SHA_INTEL}"

  url "https://github.com/infomosquitos/spacemosquito/releases/download/v#{version}/spacemosquito-darwin-#{arch}"
  name "SpaceMosquito"
  desc "Confluence space scraper, indexer and local MCP search server"
  homepage "https://github.com/infomosquitos/spacemosquito"

  livecheck do
    url :url
    strategy :github_latest
  end

  binary "spacemosquito-darwin-#{arch}", target: "spacemosquito"

  # Release binaries are not notarized; drop the quarantine flag so
  # Gatekeeper does not block the first run.
  postflight_steps do
    run "/usr/bin/xattr",
        args:           ["-d", "com.apple.quarantine", "{{staged_path}}/spacemosquito-darwin-#{arch}"],
        writable_paths: ["{{staged_path}}"],
        must_succeed:   false
  end

  zap trash: "~/.spacemosquito"

  caveats <<~EOS
    First run:
      spacemosquito init
      spacemosquito serve

    The browser extension is installed separately:
      https://github.com/infomosquitos/spacemosquito/blob/main/docs/INSTALL.md#browser-extension

    \`brew uninstall --zap spacemosquito\` also deletes ~/.spacemosquito
    (catalog, config and encryption key).
  EOS
end
EOF
